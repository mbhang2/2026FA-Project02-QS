"""Promote accumulated BWIS posteriors into bwis_config.json.

Reads a posterior dump produced after a run (or generated by the Luna agent),
computes the updated Beta parameters, and writes a new bwis_config.json with
a hard ±MAX_SHIFT cap per dimension to prevent runaway drift.

Usage (from Gowtam_hypothesis/):
    python -m bwis_probe.promote_priors \\
        --input  tmp_bwis_100/bwis_starting_weights.json \\
        --output bwis_probe/bwis_config.json \\
        --min-observations 20 \\
        --dry-run

Input format (bwis_starting_weights.json produced by luna_agent.py summarize):
    {
      "overall_bwis_score": 0.5234,
      "by_class": {"academic": {"avg_weight": 0.5806, "count": 286}, ...},
      "by_theme": {...},
      "by_backend": {...}
    }

The script prints a before/after table and aborts if any update exceeds MAX_SHIFT.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

MAX_SHIFT = 0.10        # maximum allowed mean shift in one promotion
MIN_N     = 10.0        # effective N for the Beta constructed from avg_weight


def _beta_from_mean(mean: float, n: float = MIN_N) -> dict:
    """Construct Beta(alpha, beta) from a mean and an effective observation count."""
    mean = max(0.01, min(0.99, mean))
    return {"alpha": round(mean * n, 4), "beta": round((1.0 - mean) * n, 4)}


def _mean_of(node: dict) -> float:
    a, b = node["alpha"], node["beta"]
    return a / (a + b)


def _promote_section(
    old: dict[str, dict],
    new_weights: dict[str, dict],
    section_name: str,
    min_obs: int,
    dry_run: bool,
) -> dict[str, dict]:
    """Update one section (by_class, by_theme, by_backend) key by key."""
    result = dict(old)
    for key, stats in new_weights.items():
        count = stats.get("count", 0)
        avg   = stats.get("avg_weight", None)
        if avg is None or count < min_obs:
            print(f"  [{section_name}] {key!r}: skipped (count={count} < {min_obs})")
            continue
        old_node = old.get(key)
        old_mean = _mean_of(old_node) if old_node else 0.5
        shift = abs(avg - old_mean)
        if shift > MAX_SHIFT:
            print(
                f"  [{section_name}] {key!r}: ABORTED — shift {shift:.4f} "
                f"exceeds MAX_SHIFT={MAX_SHIFT} (old={old_mean:.4f} new={avg:.4f})",
                file=sys.stderr,
            )
            raise SystemExit(1)
        new_node = _beta_from_mean(avg)
        arrow = "↑" if avg > old_mean else ("↓" if avg < old_mean else "=")
        print(
            f"  [{section_name}] {key!r}: {old_mean:.4f} → {avg:.4f} {arrow} "
            f"(shift={shift:.4f}, n={count}){' [DRY RUN]' if dry_run else ''}"
        )
        if not dry_run:
            result[key] = new_node
    return result


def aggregate_feedback(feedback_path: Path) -> dict:
    """Aggregate bwis_feedback.jsonl empirical records into prior shift statistics."""
    from collections import defaultdict
    class_counts: dict[str, int] = defaultdict(int)
    class_scores: dict[str, list[float]] = defaultdict(list)
    theme_counts: dict[str, int] = defaultdict(int)
    theme_scores: dict[str, list[float]] = defaultdict(list)
    backend_counts: dict[str, int] = defaultdict(int)
    backend_scores: dict[str, list[float]] = defaultdict(list)

    verdict_weight = {"accept": 0.85, "positive": 0.62, "flat_or_loss": 0.38}

    with open(feedback_path) as f:
        for line in f:
            if not line.strip():
                continue
            rec = json.loads(line)
            weight = verdict_weight.get(rec.get("empirical_verdict", "flat_or_loss"), 0.5)
            theme = rec.get("theme", "")
            if theme:
                theme_counts[theme] += 1
                theme_scores[theme].append(weight)
            for src in rec.get("sources", []):
                url = (src.get("source_url") or "").lower()
                backend = (src.get("backend") or "web").lower()
                backend_counts[backend] += 1
                backend_scores[backend].append(weight)

                if "arxiv" in url or "ssrn" in url or "scholar" in url:
                    src_class = "academic"
                elif any(d in url for d in ("bis.org", "federalreserve.gov", "ecb.europa.eu")):
                    src_class = "institutional"
                elif any(d in url for d in ("medium.com", "quant", "substack")):
                    src_class = "practitioner"
                else:
                    src_class = "other web"

                class_counts[src_class] += 1
                class_scores[src_class].append(weight)

    by_class = {k: {"avg_weight": sum(v) / len(v), "count": class_counts[k]} for k, v in class_scores.items()}
    by_theme = {k: {"avg_weight": sum(v) / len(v), "count": theme_counts[k]} for k, v in theme_scores.items()}
    by_backend = {k: {"avg_weight": sum(v) / len(v), "count": backend_counts[k]} for k, v in backend_scores.items()}
    return {"by_class": by_class, "by_theme": by_theme, "by_backend": by_backend}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--input", default=None,
                    help="bwis_starting_weights.json from luna_agent summarize")
    ap.add_argument("--feedback", default=None,
                    help="bwis_feedback.jsonl from campaign backtest outcomes")
    ap.add_argument("--output", required=True,
                    help="bwis_config.json to write (usually bwis_probe/bwis_config.json)")
    ap.add_argument("--min-observations", type=int, default=20,
                    help="minimum source count to update a prior (default: 20)")
    ap.add_argument("--dry-run", action="store_true",
                    help="print the diff without writing the file")
    args = ap.parse_args()

    if not args.input and not args.feedback:
        print("Must specify either --input or --feedback", file=sys.stderr)
        return 1

    outp = Path(args.output)

    if args.feedback:
        fb_path = Path(args.feedback)
        if not fb_path.exists():
            print(f"feedback file not found: {fb_path}", file=sys.stderr)
            return 1
        new_weights = aggregate_feedback(fb_path)
        source_label = str(fb_path)
    else:
        inp = Path(args.input)
        if not inp.exists():
            print(f"input not found: {inp}", file=sys.stderr)
            return 1
        with open(inp) as f:
            new_weights = json.load(f)
        source_label = str(inp)

    if not outp.exists():
        print(f"config not found at {outp}; creating from scratch", file=sys.stderr)
        old_cfg: dict = {"by_class": {}, "by_theme": {}, "by_backend": {}}
    else:
        with open(outp) as f:
            old_cfg = json.load(f)

    print(f"\nPromoting priors: {source_label} → {outp}")
    print(f"min_observations={args.min_observations}, MAX_SHIFT={MAX_SHIFT}, dry_run={args.dry_run}\n")

    new_cfg = dict(old_cfg)

    # Global floor
    overall = new_weights.get("overall_bwis_score")
    if overall is not None:
        old_floor = old_cfg.get("global_floor", {"alpha": 5.0, "beta": 5.0})
        old_mean  = _mean_of(old_floor)
        shift = abs(overall - old_mean)
        if shift > MAX_SHIFT:
            print(f"global_floor: ABORTED — shift {shift:.4f} > {MAX_SHIFT}", file=sys.stderr)
            return 1
        print(f"  [global_floor]: {old_mean:.4f} → {overall:.4f} (shift={shift:.4f})")
        if not args.dry_run:
            new_cfg["global_floor"] = _beta_from_mean(overall)

    # Sections
    for section in ("by_class", "by_theme", "by_backend"):
        new_section = _promote_section(
            old_cfg.get(section, {}),
            new_weights.get(section, {}),
            section,
            args.min_observations,
            args.dry_run,
        )
        if not args.dry_run:
            new_cfg[section] = new_section

    if not args.dry_run:
        # Preserve comments / metadata keys from the old config
        new_cfg.setdefault("_comment", old_cfg.get("_comment", ""))
        new_cfg["_source"] = str(inp)
        with open(outp, "w") as f:
            json.dump(new_cfg, f, indent=2)
        print(f"\nWritten: {outp}")
    else:
        print("\n[DRY RUN] No files written.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
