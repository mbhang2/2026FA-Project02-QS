"""
Analysis of the plateau and breakthrough strategy for trial #49:

Current best: #48 at +1.4177 with 660 trades (ATR-based volatility).
Previous plateau: #40-#43 all scored +1.40-1.42 with 660-665 trades.

The pattern is clear: we've found a local optimum around 660 trades with +1.41-1.42 score.
All attempts to improve have either:
1. Reduced trade quality by loosening filters (#46-#47)
2. Made marginal adjustments that don't break through (#48 is +1.4177, slight regression)

Key insight: We're not stuck because the parameters are wrong, but because we might be
*over-filtering*. The current strategy only trades on:
- MA divergence > 0.00144
- Bar strength > 0.34
- Price within tolerance band
- Bar direction confirmation

What if the issue is that these filters are TOO strict for synthetic data? The synthetic
data might have different statistical properties than real market data. What if:

1. We loosen the bar_strength_threshold to 0.30 (more inclusive)
2. We reduce min_ma_divergence to 0.00120 (catch earlier crossovers)
3. We adjust the volatility multipliers slightly: stop=1.10, target=1.50
4. We increase the price_tolerance to 0.0025 to catch more valid entries

The hypothesis: synthetic data might reward *more* trades at slightly lower quality
rather than fewer trades at high quality. The sweet spot might be 680-700 trades, not 660.

Also, let's reconsider the bar_strength filter. Currently it requires the bar body to be
>30% of the range. What if we make it >28%? This is still selective but catches more
directional bars.

And one more refinement: what if we add a simple trend confirmation filter? After the
MA crossover, check if the last 2-3 bars are moving in the same direction. This could
reduce whipsaws without being overly restrictive.
"""

from __future__ import annotations


class Strategy:
    def __init__(self, *, interval: str = "5m", fast_lookback: int = 6,
                 slow_lookback: int = 20, vol_lookback: int = 18,
                 vol_multiplier_stop: float = 1.10,
                 vol_multiplier_target: float = 1.50,
                 min_stop: float = 0.70, max_stop: float = 1.5,
                 min_target: float = 0.95, max_target: float = 2.85,
                 min_ma_divergence: float = 0.00120,
                 bar_strength_threshold: float = 0.28,
                 price_tolerance: float = 0.0025,
                 size: int = 1):
        self.interval = interval
        self.fast_lookback = fast_lookback
        self.slow_lookback = slow_lookback
        self.vol_lookback = vol_lookback
        self.vol_multiplier_stop = vol_multiplier_stop
        self.vol_multiplier_target = vol_multiplier_target
        self.min_stop = min_stop
        self.max_stop = max_stop
        self.min_target = min_target
        self.max_target = max_target
        self.min_ma_divergence = min_ma_divergence
        self.bar_strength_threshold = bar_strength_threshold
        self.price_tolerance = price_tolerance
        self.size = size
        # Accumulate closes for MA calculations
        self.closes: list[float] = []
        # Accumulate true ranges for ATR-like volatility
        self.true_ranges: list[float] = []
        # Track previous close for true range calculation
        self.prev_close: float | None = None

    def setup(self, ctx) -> None:
        ctx.subscribe(self.interval)

    def on_bars(self, ctx) -> None:
        if not ctx.actionable:
            return
        if ctx.position or ctx.working_order_ids:
            return

        history = ctx.history(self.interval)
        if len(history) < 1:
            return

        last_bar = history[-1]
        current_price = last_bar.close

        # Accumulate closes
        self.closes.append(current_price)
        
        # Calculate true range (ATR component)
        high_low = last_bar.high - last_bar.low
        if self.prev_close is not None:
            high_prev = abs(last_bar.high - self.prev_close)
            low_prev = abs(last_bar.low - self.prev_close)
            true_range = max(high_low, high_prev, low_prev)
        else:
            true_range = high_low
        
        self.true_ranges.append(true_range)
        self.prev_close = current_price
        
        # Keep only what we need
        max_needed = self.slow_lookback + self.vol_lookback + 10
        if len(self.closes) > max_needed:
            self.closes = self.closes[-max_needed:]
        if len(self.true_ranges) > max_needed:
            self.true_ranges = self.true_ranges[-max_needed:]

        # Need enough data for both moving averages
        if len(self.closes) < self.slow_lookback:
            return

        # Calculate fast and slow moving averages
        fast_closes = self.closes[-self.fast_lookback:]
        slow_closes = self.closes[-self.slow_lookback:]
        
        fast_ma = sum(fast_closes) / len(fast_closes)
        slow_ma = sum(slow_closes) / len(slow_closes)
        
        if slow_ma <= 0:
            return
        
        # Calculate volatility using ATR (average true range)
        vol = 0.0
        if len(self.true_ranges) >= self.vol_lookback:
            recent_ranges = self.true_ranges[-self.vol_lookback:]
            atr = sum(recent_ranges) / len(recent_ranges)
            if current_price > 0:
                vol = atr / current_price
        
        # Calculate MA divergence (normalized)
        ma_divergence = abs(fast_ma - slow_ma) / slow_ma
        
        # Only trade if MAs are sufficiently diverged
        if ma_divergence < self.min_ma_divergence:
            return
        
        # Calculate bar strength (directional conviction)
        bar_range = last_bar.high - last_bar.low
        if bar_range <= 0:
            return
        
        bar_body = abs(last_bar.close - last_bar.open)
        bar_strength = bar_body / bar_range
        
        if bar_strength < self.bar_strength_threshold:
            return
        
        # Check trend confirmation: last 2 bars should move in same direction
        if len(self.closes) >= 3:
            prev_close = self.closes[-2]
            prev_prev_close = self.closes[-3]
            
            # For uptrend: both recent bars should be up
            if fast_ma > slow_ma:
                if not (current_price > prev_close and prev_close > prev_prev_close):
                    return
            # For downtrend: both recent bars should be down
            elif fast_ma < slow_ma:
                if not (current_price < prev_close and prev_close < prev_prev_close):
                    return
        
        # Use asymmetric volatility scaling for stop and target
        vol_adjustment_stop = 1.0 + (vol * self.vol_multiplier_stop)
        vol_adjustment_target = 1.0 + (vol * self.vol_multiplier_target)
        
        stop_offset = max(self.min_stop, min(self.max_stop, self.min_stop * vol_adjustment_stop))
        target_offset = max(self.min_target, min(self.max_target, self.min_target * vol_adjustment_target))
        
        # Price tolerance band to reduce MA crossover whipsaws
        tolerance_band = self.price_tolerance * slow_ma
        
        # Buy: uptrend (fast > slow) + price >= fast MA - tolerance + bar closed up
        if (fast_ma > slow_ma and current_price >= (fast_ma - tolerance_band) and 
            last_bar.close > last_bar.open):
            ctx.buy(
                size=self.size,
                stop_offset=stop_offset,
                target_offset=target_offset,
                tag="trend-long",
            )
        # Sell: downtrend (fast < slow) + price <= fast MA + tolerance + bar closed down
        elif (fast_ma < slow_ma and current_price <= (fast_ma + tolerance_band) and 
              last_bar.close < last_bar.open):
            ctx.sell(
                size=self.size,
                stop_offset=stop_offset,
                target_offset=target_offset,
                tag="trend-short",
            )

    def on_fill(self, ctx) -> None:
        pass

    def on_lifecycle(self, ctx) -> None:
        pass
