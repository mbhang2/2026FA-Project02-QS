"""Stub proposal functions. No LLM anywhere in this file, deliberately.

The project's contribution is the correction over the trial ledger, and a
correction cannot be checked against a campaign whose ground truth is unknown.
**The null generator proposes strategies that have no edge by construction**, so
a campaign of them has a known answer: zero real discoveries. Anything the
correction reports above that is a false one, and counting them is the
calibration.

It also means the loop's machinery is debugged against something deterministic
rather than against a model that answers differently every time.

`propose(history) -> str` returns strategy source. `history` is passed and
ignored: **what a real agent should see is a Task 31 decision** and it is a real
one -- showing prior trials and their scores is what makes this research rather
than random search, and it is also what makes trials correlated, which changes
what the correction's raw N means. Baking an answer in here would settle it by
accident.
"""

from __future__ import annotations

import random
from dataclasses import dataclass, field
from pathlib import Path
from typing import Protocol, Sequence

from .._roots import repo_root

# Was `Path(__file__).resolve().parents[3]`. The nine modules under
# src/core/ counted at three different depths, which is the evidence
# that a count describes this file rather than the repository.
REPO_ROOT = repo_root()


class StubAgent(Protocol):
    """What the loop calls. A real agent implements the same one method."""

    def propose(self, history: Sequence[dict]) -> str: ...


# The shape every null proposal takes. Momentum on the last closed bar, which on
# pure-noise data has no edge by construction -- the same property that makes it
# the calibration reference. What varies is the parameters, and none of them can
# create an edge in a series that has none.
NULL_TEMPLATE = '''"""Generated by the loop's null stub. No edge by construction.

Momentum on the last closed bar of a {interval} series, bracketed at
{stop}/{target}. On the synthetic generator's pure-noise sessions there is
nothing for this to find, whatever the parameters, which is exactly why it is
what the correction is calibrated against.
"""

from __future__ import annotations


class Strategy:
    def setup(self, ctx) -> None:
        ctx.subscribe("{interval}")

    def on_bars(self, ctx) -> None:
        if ctx.position or ctx.working_order_ids:
            return
        history = ctx.history("{interval}")
        if len(history) < {lookback}:
            return
        last = history[-1]
        if last.close == last.open:
            return
        rising = last.close > last.open
        place = ctx.buy if rising is {follow} else ctx.sell
        place(size={size}, stop_offset={stop}, target_offset={target}, tag="entry")

    def on_fill(self, ctx) -> None:
        pass

    def on_lifecycle(self, ctx) -> None:
        pass
'''

CRASH_TEMPLATE = '''"""Generated by the loop's null stub, and deliberately broken.

A crashed trial is still a trial: it gets a row, `outcome: crashed`,
`score: null`, and it counts toward N. A campaign whose failures quietly vanish
has a denominator smaller than the number of things it looked at, which is the
most natural way to cheat a multiple-testing correction and the one nobody would
notice.
"""

from __future__ import annotations


class Strategy:
    def setup(self, ctx) -> None:
        ctx.subscribe("5m")

    def on_bars(self, ctx) -> None:
        raise RuntimeError("deliberate: the stub's crash fraction")

    def on_fill(self, ctx) -> None:
        pass

    def on_lifecycle(self, ctx) -> None:
        pass
'''


@dataclass
class NullGenerator:
    """Edgeless variants by parameter jitter. Deterministic given `seed`.

    `crash_fraction` exists so failure accounting can be verified end to end
    rather than asserted. It is a property of the stub, not of the loop, and the
    campaign record carries it.
    """

    seed: int = 0
    crash_fraction: float = 0.0
    intervals: tuple[str, ...] = ("1m", "5m", "15m")
    _rng: random.Random = field(init=False, repr=False)
    _n: int = field(default=0, init=False, repr=False)

    def __post_init__(self) -> None:
        self._rng = random.Random(self.seed)

    def propose(self, history: Sequence[dict]) -> str:
        del history                      # a Task 31 decision; see the module docstring
        self._n += 1
        if self._rng.random() < self.crash_fraction:
            return CRASH_TEMPLATE
        return NULL_TEMPLATE.format(
            interval=self._rng.choice(self.intervals),
            stop=round(self._rng.uniform(0.25, 2.0), 4),
            target=round(self._rng.uniform(0.25, 2.0), 4),
            size=self._rng.choice((1, 1, 1, 2)),
            lookback=self._rng.choice((1, 1, 2, 3)),
            # Following or fading the last bar. Both are edgeless on noise; the
            # variety is here so the campaign is not 200 copies of one strategy
            # with different brackets.
            follow=self._rng.choice((True, False)),
        )


@dataclass
class ReplayList:
    """A fixed sequence of sources. For tests that need the loop deterministic
    down to the byte, without a generator between them and the answer."""

    sources: Sequence[str]
    _n: int = field(default=0, init=False, repr=False)

    def propose(self, history: Sequence[dict]) -> str:
        del history
        source = self.sources[self._n % len(self.sources)]
        self._n += 1
        return source
