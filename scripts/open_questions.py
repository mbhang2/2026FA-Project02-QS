#!/usr/bin/env python3
"""Questions we asked and could not answer, for the retrieval side to match on.

    python scripts/open_questions.py
    python scripts/open_questions.py --json

The ranker judges a paper against two things: questions we have **closed**, and
lines each hypothesis wrote under *what this is not asking for*. Task 71 §14
found that the second list is not what it was labelled -- it is permanent data
constraints and standing decisions, so a paper "speaking to" one is proposing
what we declined.

**That leaves the kind a paper can actually help with missing entirely.** A
question we asked, ran a campaign on, and did not resolve is exactly what a
literature search is for, and nothing in this project recorded one. The
material exists: four auditors read every campaign, and what they object to is
very often an open question in the form of a complaint --

    "the strategy's edge is concentrated in specific intraday windows with no
     stated rationale for why those windows would persist"

That is not a defect report. It is a question about the mechanism, generated by
our own run, and until now it reached nobody.

## Where they come from, and the one hard line

Only from seats that **VETO** or say **CANNOT_TELL**. A PASS has no complaint in
it, and a seat that passed is not telling us anything unresolved.

**Only from campaigns with no validation artefact at all.** §4: campaign k+1 may
depend on prior campaigns' train results, never on their validation results, and
the honest reading is that the information must not be in the room. The committee
is validation-informed whenever the report stage ran after validation --
`record_outcome.py` says so in as many words -- and four campaigns are in exactly
that state (`nq-ml-02`, `nq-ml-03`, `nq-orderflow-01`, `nq-orderflow-02`). They
are refused here. It is the same rule `refine_hypothesis.py` applies, deliberately
stated once and used twice rather than reasoned about twice.

## Nothing is rewritten

The objections are quoted verbatim. No model turns them into questions, because
a model writing our open questions is a model inventing research directions, and
this project has spent the week finding out what unchecked generation costs. The
ranker is an LLM and can read a complaint as a question without help.
"""
from __future__ import annotations

import argparse
import difflib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAMPAIGNS = ROOT / "runs" / "campaigns"

UNRESOLVED = ("VETO", "CANNOT_TELL")

# An auditor that did not run is recorded as a VETO with its failure as the
# "reason", which is the right refusal -- `no verdict is not no veto` -- and is
# not an objection. Two were in the first draft of this list: a reply that was
# not JSON, and a reply whose 16,384-token budget went entirely to reasoning.
# They are dropped from the questions and counted separately, because a seat
# that never ran is a fact about our endpoint and not about the market.
NOT_AN_OBJECTION = ("the auditor did not run", "reply was not JSON",
                    "empty reply:", "LLMUnavailable", "finish_reason=")
MAX_QUESTIONS = 12
SIMILAR = 0.72        # above this, two objections are the same objection


FAILED_SEATS: list[dict] = []


def eligible(name: str) -> tuple[bool, str]:
    """Whether this campaign's committee may be read. Same rule as the refiner."""
    d = CAMPAIGNS / name
    if not (d / "committee-verdict.json").exists():
        return False, "no committee verdict"
    leak = sorted(p.name for p in d.glob("validation*") if p.is_file())
    if leak:
        return False, (f"validation artefact present ({', '.join(leak)}), so the "
                       f"committee may have been shown a validation number")
    return True, ""


def collect() -> list[dict]:
    """Every unresolved objection, verbatim, with where it came from."""
    out: list[dict] = []
    for d in sorted(CAMPAIGNS.glob("*")):
        ok, _why = eligible(d.name)
        if not ok:
            continue
        try:
            v = json.loads((d / "committee-verdict.json").read_text())
        except Exception:                                        # noqa: BLE001
            continue
        for a in v.get("auditors") or []:
            if str(a.get("verdict", "")).upper() not in UNRESOLVED:
                continue
            for r in a.get("reasons") or []:
                if any(m in str(r) for m in NOT_AN_OBJECTION):
                    FAILED_SEATS.append({"campaign": d.name,
                                         "axis": a.get("axis"),
                                         "why": str(r)[:150]})
                    continue
                out.append({"campaign": d.name, "axis": a.get("axis"),
                            "verdict": a.get("verdict"), "objection": str(r)})
        t3 = d / "tier3-verdict.json"
        if t3.exists():
            try:
                t = json.loads(t3.read_text())
            except Exception:                                    # noqa: BLE001
                t = {}
            if str(t.get("verdict", "")).upper() == "CANNOT_TELL":
                note = t.get("note") or t.get("reason") or "tier 3 CANNOT_TELL"
                out.append({"campaign": d.name, "axis": "tier3",
                            "verdict": "CANNOT_TELL", "objection": str(note)})
    return out


MAX_PER_CAMPAIGN = 2
OBJECTION_CHARS = 320


def _round_robin(items: list[dict]) -> list[dict]:
    """One objection per campaign, then a second, and so on.

    **Taking the first N takes them all from one campaign.** Sorted order put
    `nq-mvp-01` first and it filled every slot -- twelve objections about a
    champion that traded three times, which is a true complaint and not a
    question any paper answers. The open questions should span the project.
    """
    by: dict[str, list[dict]] = {}
    for it in items:
        by.setdefault(it["campaign"], []).append(it)
    out, depth = [], 0
    while depth < MAX_PER_CAMPAIGN:
        added = False
        for name in sorted(by):
            if len(by[name]) > depth:
                out.append(by[name][depth])
                added = True
        if not added:
            break
        depth += 1
    return out


def distinct(items: list[dict], limit: int = MAX_QUESTIONS) -> list[dict]:
    """Drop near-duplicates, spread across campaigns. The same complaint recurs
    -- every robustness seat objects to concentration -- and twelve phrasings of
    one question is eleven wasted lines of context, not twelve open questions."""
    kept: list[dict] = []
    for it in _round_robin(items):
        text = it["objection"].lower()
        if any(difflib.SequenceMatcher(None, text, k["objection"].lower())
               .ratio() > SIMILAR for k in kept):
            for k in kept:
                if difflib.SequenceMatcher(None, text,
                                           k["objection"].lower()).ratio() > SIMILAR:
                    k.setdefault("also", []).append(it["campaign"])
                    break
            continue
        q = dict(it)
        if len(q["objection"]) > OBJECTION_CHARS:
            q["objection"] = q["objection"][:OBJECTION_CHARS].rsplit(" ", 1)[0] + " ..."
        kept.append(q)
        if len(kept) >= limit:
            break
    return kept


def block(limit: int = MAX_QUESTIONS) -> str:
    """The section the ranker is given. Empty string when there is nothing."""
    qs = distinct(collect(), limit)
    if not qs:
        return ""
    lines = [
        "### Asked and unresolved -- what a paper could actually help with\n",
        "Objections raised by the four auditors on campaigns we ran, quoted "
        "verbatim. Each is a question our own data raised and did not answer. "
        "**Unlike the exclusion list above, a paper that speaks to one of these "
        "IS worth more** -- this is the kind criterion 2 means.\n",
    ]
    for q in qs:
        also = q.get("also") or []
        where = q["campaign"] + (f" (and {len(also)} other campaign(s))"
                                 if also else "")
        lines.append(f"- **{q['axis']}**, {where}: {q['objection']}\n")
    return "".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--limit", type=int, default=MAX_QUESTIONS)
    a = ap.parse_args()

    allc = sorted(p.name for p in CAMPAIGNS.glob("*") if p.is_dir())
    usable, refused = [], []
    for n in allc:
        ok, why = eligible(n)
        (usable if ok else refused).append((n, why))

    raw = collect()
    qs = distinct(raw, a.limit)
    if a.json:
        print(json.dumps({"questions": qs, "raw_count": len(raw),
                          "failed_seats": FAILED_SEATS,
                          "campaigns_used": [n for n, _ in usable],
                          "campaigns_refused": {n: w for n, w in refused if w}},
                         indent=2))
        return 0

    print(f"campaigns readable: {len(usable)}   refused: "
          f"{len([1 for _, w in refused if w])}")
    for n, w in refused:
        if w and "no committee" not in w:
            print(f"  REFUSED {n}: {w}")
    print(f"\n{len(raw)} unresolved objection(s) -> {len(qs)} distinct")
    if FAILED_SEATS:
        print(f"\n{len(FAILED_SEATS)} seat(s) never ran and were dropped -- a "
              f"failed auditor is a fact about our endpoint, not the market:")
        for f in FAILED_SEATS[:6]:
            print(f"  {f['campaign']:22} {f['axis']}: {f['why'][:92]}")
    print()
    print(block(a.limit))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
