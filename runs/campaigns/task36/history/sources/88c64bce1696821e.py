"""
Breakout strategy over a 5-bar window.

Builds on the successful breakout strategy (Trial #0) by reducing the lookback
from 6 to 5 bars to increase the number of trading opportunities. The stop
and target multipliers are scaled slightly (from 1.0/2.0 to 1.1/2.2) to account for
the smaller measured range of a 5-bar window, aiming to maintain the optimal
absolute bracket distances while capturing more moves.
"""

class Strategy:
    def __init__(self, interval="5m", lookback=5, size=1, stop_mult=1.1, target_mult=2.2):
        self.interval = interval
        self.lookback = lookback
        self.size = size
        self.stop_mult = stop_mult
        self.target_mult = target_mult

    def setup(self, ctx):
        ctx.subscribe(self.interval)

    def on_bars(self, ctx):
        if not ctx.actionable or ctx.position or ctx.working_order_ids:
            return

        history = ctx.history(self.interval)
        if len(history) < self.lookback + 1:
            return

        window = history.last(self.lookback + 1)
        last, prior = window[-1], window[:-1]
        
        high = max(b.high for b in prior)
        low = min(b.low for b in prior)
        rng = high - low
        if rng <= 0:
            return

        stop = rng * self.stop_mult
        target = rng * self.target_mult

        if last.close > high:
            ctx.buy(
                size=self.size, 
                stop_offset=stop, 
                target_offset=target, 
                tag="breakout-long"
            )
        elif last.close < low:
            ctx.sell(
                size=self.size, 
                stop_offset=stop, 
                target_offset=target, 
                tag="breakout-short"
            )

    def on_fill(self, ctx):
        pass

    def on_lifecycle(self, ctx):
        pass
