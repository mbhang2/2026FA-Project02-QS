#!/usr/bin/env python3
"""Write `requirements.lock` from the environment that is actually installed.

    python scripts/lock_env.py            # rewrite the lockfile
    python scripts/lock_env.py --check    # does it match THIS environment?
    python scripts/lock_env.py --verify   # CI: is it internally consistent?

`--check` and `--verify` are different questions and CI can only ask the second.
The lockfile records the environment that *produces scored runs* -- the machine
with bucket credentials -- and CI is a different environment by construction: it
installs from `requirements-dev.txt` on a different platform. Running `--check`
there would fail forever for a reason that is not a problem. So CI asks whether
the lockfile is well formed and does not contradict `requirements.txt`, and the
person on the machine that produces runs asks `--check`.

A row records the environment it was actually produced under
(`environment_fingerprint`) as well as the lockfile it declared
(`lockfile_digest`), so the pair still answers the real question per row, and
`scripts/ledger_check.py` reports the difference as environment-drifted.

Task 22 named the gap and could not close it with a hash: numpy and pandas
versions change numbers, and no digest over the repo's own files can see that.
So the environment is pinned in a committed file and a run record carries the
file's digest beside `code_fingerprint`, plus a digest of what was *actually*
imported at run time. The pair is the point -- the first says what was declared,
the second says what ran, and a difference between them is the interesting case.

The editable install of this repo is excluded: its version string moves with
every commit and that is already covered by `git_sha`.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LOCKFILE = REPO_ROOT / "requirements.lock"

HEADER = """\
# Generated by scripts/lock_env.py -- do not hand-edit.
#
# The full transitive set, pinned. Task 22 named the gap this closes: numpy and
# pandas versions change numbers, and no content hash over the repo can see that.
# `code_fingerprint` says the code was the committed code; this says the
# environment was the declared environment, and a run record carries a digest of
# both.
#
# The editable install of this repo is excluded on purpose: its version string
# moves with every commit, which would make the lockfile's digest change for
# reasons that are already covered by `git_sha` and `code_fingerprint`.
"""


def resolved() -> str:
    out = subprocess.run(
        [sys.executable, "-m", "pip", "freeze", "--exclude-editable"],
        capture_output=True, text=True, check=True,
    ).stdout
    pins = sorted(line for line in out.splitlines() if "==" in line)
    return HEADER + "\n".join(pins) + "\n"


def _pins(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if "==" in line:
            name, version = line.split("==", 1)
            out[name.strip().lower().replace("_", "-")] = version.strip()
    return out


def verify() -> int:
    """Is the lockfile internally consistent, and does it agree with what the
    repo asks for? The question CI can answer."""
    if not LOCKFILE.exists():
        print("requirements.lock is missing; run scripts/lock_env.py",
              file=sys.stderr)
        return 1
    text = LOCKFILE.read_text()
    locked = _pins(text)
    if not locked:
        print("requirements.lock pins nothing", file=sys.stderr)
        return 1

    names = [line.split("==")[0].strip().lower().replace("_", "-")
             for line in text.splitlines() if "==" in line]
    duplicates = sorted({n for n in names if names.count(n) > 1})
    if duplicates:
        print(f"requirements.lock pins these more than once: {duplicates}",
              file=sys.stderr)
        return 1

    problems = []
    for source in (REPO_ROOT / "requirements.txt", REPO_ROOT / "requirements-dev.txt"):
        if not source.exists():
            continue
        for name, version in _pins(source.read_text()).items():
            if name not in locked:
                problems.append(f"{source.name} pins {name} and the lock does not")
            elif locked[name] != version:
                problems.append(
                    f"{source.name} pins {name}=={version}, "
                    f"the lock says {locked[name]}"
                )
    if problems:
        print("requirements.lock contradicts the declared dependencies:",
              file=sys.stderr)
        for line in problems:
            print(f"  {line}", file=sys.stderr)
        return 1

    print(f"requirements.lock is consistent ({len(locked)} pins, "
          f"agrees with requirements.txt and requirements-dev.txt)")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the lockfile is not what this "
                         "environment would produce")
    ap.add_argument("--verify", action="store_true",
                    help="CI: the lockfile parses, pins every name once, and "
                         "does not contradict requirements.txt")
    args = ap.parse_args(argv)

    if args.verify:
        return verify()

    current = resolved()
    if args.check:
        on_disk = LOCKFILE.read_text() if LOCKFILE.exists() else ""
        if on_disk == current:
            print(f"requirements.lock is current ({current.count('==')} pins)")
            return 0
        print("requirements.lock does not match this environment. Either the "
              "environment drifted or the lockfile was not regenerated:",
              file=sys.stderr)
        want = {line.split("==")[0]: line for line in on_disk.splitlines() if "==" in line}
        have = {line.split("==")[0]: line for line in current.splitlines() if "==" in line}
        for name in sorted(set(want) | set(have)):
            if want.get(name) != have.get(name):
                print(f"  {want.get(name, '(absent)')}  ->  {have.get(name, '(absent)')}",
                      file=sys.stderr)
        return 1

    LOCKFILE.write_text(current)
    print(f"wrote {LOCKFILE.relative_to(REPO_ROOT)}  ({current.count('==')} pins)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
