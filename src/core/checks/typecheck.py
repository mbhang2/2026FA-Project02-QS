"""Type-check the agent's file against `src.core.types.Strategy`.

Static, like everything else here: mypy parses and infers, it does not import the
module it is analysing. That is the property that matters -- a type checker that
ran the code would reopen the oracle the AST layer exists to close.

The conformance file is generated rather than committed because the class name is
not fixed: `run.load_strategy()` accepts `STRATEGY`, `Strategy` or
`MomentumStrategy`, and the check has to assert conformance for whichever one the
loader would pick. It is written to a scratch directory and thrown away.

Constructing the strategy in the generated file is deliberate. `load_strategy()`
calls `obj()` with no arguments, so a strategy whose `__init__` requires one
cannot be run by the harness, and the type error saying so is the accurate
message rather than an artefact of how this check is written.
"""

from __future__ import annotations

import tempfile
import threading
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]

CONFORMANCE = '''\
# generated by src/core/checks/typecheck.py -- not committed, not imported
from src.core.types import Strategy as _Protocol
from {module} import {name} as _Impl


def _conforms(strategy: _Protocol) -> None: ...


_conforms({expression})
'''

MYPY_ARGS = (
    # The strategy may import anything; missing stubs for a third-party library
    # are not the agent's mistake and must not read as one.
    "--ignore-missing-imports",
    # Analyse the harness enough to know what the Protocol requires, without
    # reporting the harness's own type debt as a finding against the strategy.
    "--follow-imports=silent",
    "--no-error-summary",
    "--no-color-output",
    "--hide-error-context",
)


@dataclass(frozen=True, slots=True)
class TypeResult:
    ok: bool
    errors: tuple[str, ...]
    skipped_reason: str = ""


def _mypy_available() -> str:
    try:
        import mypy.api  # noqa: F401
    except ImportError:
        return ("mypy is not installed, so the type layer of the check cannot "
                "run. `pip install -r requirements-dev.txt`.")
    return ""


def type_check(strategy_path: Path, class_name: str,
               module: str = "src.strategies.current") -> TypeResult:
    """mypy over the strategy plus a generated conformance assertion.

    A missing mypy is a **failure**, not a skip. A check that quietly does less
    than it says is the shape of every problem in this file's history.
    """
    unavailable = _mypy_available()
    if unavailable:
        return TypeResult(ok=False, errors=(unavailable,), skipped_reason=unavailable)

    from mypy import api

    with _MYPY_LOCK:
        return _run_mypy(api, strategy_path, class_name, module)


# mypy's Python API keeps process-global state and is **not safe to call from
# two threads at once**. Task 36 found out the expensive way: the control arm
# generates its proposals concurrently, six threads reached `type_check`, and
# mypy answered with `INTERNAL ERROR ... _hashlib.pyi:26`. That lands in stderr,
# `type_check` reports it as a finding, and the agent is sent away to repair a
# file that was fine -- a harness failure wearing a candidate failure's clothes,
# on the path whose whole job is to keep those two apart.
#
# The lock costs nothing that matters: a check is ~0.4s and there are a hundred
# of them.
_MYPY_LOCK = threading.Lock()


def _run_mypy(api, strategy_path: Path, class_name: str, module: str) -> TypeResult:

    # `STRATEGY` is an instance; the others are classes the loader instantiates.
    expression = "_Impl" if class_name == "STRATEGY" else "_Impl()"
    with tempfile.TemporaryDirectory() as tmp:
        conformance = Path(tmp) / "_conformance.py"
        conformance.write_text(
            CONFORMANCE.format(module=module, name=class_name, expression=expression)
        )
        cache = Path(tmp) / "cache"
        stdout, stderr, _ = api.run([
            *MYPY_ARGS,
            "--cache-dir", str(cache),
            str(strategy_path),
            str(conformance),
        ])

    interesting = []
    for line in (stdout or "").splitlines():
        if not line.strip() or ": note:" in line:
            continue
        # Rewrite the scratch path out of the message: the agent has no scratch
        # directory and a finding pointing at one is unactionable noise.
        if "_conformance.py" in line:
            line = (
                "does not satisfy the Strategy protocol: "
                + line.split(": error: ", 1)[-1]
            )
        interesting.append(line.strip())
    if stderr and stderr.strip():
        interesting.append(f"mypy: {stderr.strip()}")
    return TypeResult(ok=not interesting, errors=tuple(interesting))
